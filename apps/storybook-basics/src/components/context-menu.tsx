import { cn } from "../lib/utils";
import { ToolbarBoundary } from "./toolbar";

function ContextMenu({ ...props }: ContextMenuPrimitive.Root.Props) {
  return <ContextMenuPrimitive.Root data-slot="context-menu" {...props} />;
}

function ContextMenuPortal({ children, ...props }: ContextMenuPrimitive.Portal.Props) {
  // Same boundary the Content wrapper applies. This raw wrapper is EXPORTED,
  // so a consumer portalling their own content through it was still leaking
  // toolbar context across the portal — the Content fix covered the kit's
  // own usage and missed the public seam (judge fixture, 2026-09-18).
  return (
    <ContextMenuPrimitive.Portal data-slot="context-menu-portal" {...props}>
      <ToolbarBoundary>{children}</ToolbarBoundary>
    </ContextMenuPrimitive.Portal>
  );
}

function ContextMenuTrigger({
  className,
  ...props
}: ContextMenuPrimitive.Trigger.Props) {
  return (
    <ContextMenuPrimitive.Trigger
      data-slot="context-menu-trigger"
      className={cn("select-none", className)}
      {...props}
    />
  );
}

function ContextMenuContent({
  className,
  align = "start",
  alignOffset = 4,
  side = "right",
  sideOffset = 0,
  container,
  positionerClassName,
  ...props
}: ContextMenuPrimitive.Popup.Props &
  Pick<
    ContextMenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  > &
  Pick<ContextMenuPrimitive.Portal.Props, "container"> & {
    // WHY these two additions to a generated file (ported verbatim from the
    // donor, same reasoning as dropdown-menu.tsx's `anchor` widening): Base
    // UI puts a popup's stacking on the POSITIONER (a z-index on the popup
    // is already inside the positioner's `isolate z-50` context and can
    // never escape it), and the portal defaults to `<body>` — outside
    // whatever token-scoping element the host wraps its app in, where none
    // of the shadcn CSS variables resolve, so the menu paints unthemed.
    // Both are host facts a component cannot know, so they arrive as props.
    positionerClassName?: string;
  }) {
  return (
    <ContextMenuPrimitive.Portal container={container}>
      {/* Resets `useInsideToolbar` — React context crosses a portal but the
          DOM does not, so a ControlStrip opened from a toolbar would
          otherwise render as a group with no toolbar ancestor and leak
          arrow-key focus back to that toolbar. See toolbar.tsx's
          `ToolbarBoundary`. */}
      <ToolbarBoundary>
        <ContextMenuPrimitive.Positioner
          className={cn("isolate z-50 outline-none", positionerClassName)}
          align={align}
          alignOffset={alignOffset}
          side={side}
          sideOffset={sideOffset}
        >
          <ContextMenuPrimitive.Popup
            data-slot="context-menu-content"
            className={cn(
              "data-open:animate-in data-closed:animate-out data-closed:fade-out-0 data-open:fade-in-0 data-closed:zoom-out-95 data-open:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 ring-foreground/10 bg-popover text-popover-foreground min-w-36 rounded-lg p-1 shadow-md ring-1 duration-100 max-h-(--available-height) origin-(--transform-origin) overflow-x-hidden overflow-y-auto outline-none data-closed:overflow-hidden",
              className,
            )}
            {...props}
          />
        </ContextMenuPrimitive.Positioner>
      </ToolbarBoundary>
    </ContextMenuPrimitive.Portal>
  );
}

