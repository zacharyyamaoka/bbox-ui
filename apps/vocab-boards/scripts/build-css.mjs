#!/usr/bin/env node
/**
 * Writes dist/board.css: this app's own stylesheet plus the subset of
 * @xyflow/react's stylesheet that STATIC markup needs.
 *
 * WHY a derived subset and not a hand-copied block: the report inlines this once
 * for all 705 boards and never loads React Flow, so the rules have to be here —
 * but a hand-copied block goes stale silently the next time xyflow moves a
 * selector. This reads the installed base.css and filters it, so an upstream
 * rename shows up as a MISSING rule at build time, not as 705 broken figures.
 *
 * WHY the `.react-flow ` ancestor is stripped: the captured markup is the
 * `.react-flow__viewport` element alone — it has no `.react-flow` ancestor in
 * the report, so `.react-flow .react-flow__edges { position: absolute }` would
 * never match and every wire would stack at the top-left corner.
 */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "..");
const require = createRequire(import.meta.url);

/** Selectors the static markup actually depends on. */
const KEEP = [
  // The captured element itself carries `react-flow__container`, which is what
  // makes it fill its wrapper — without it every board collapses to zero size.
  ".react-flow__container",
  ".react-flow__viewport",
  ".react-flow__viewport-portal",
  ".react-flow__nodes",
  ".react-flow__node",
  ".react-flow__edges",
  ".react-flow__edge",
  ".react-flow__edge-path",
  ".react-flow__handle",
];

/** Rules that would be wrong once the markup is out of the app. */
const DROP = [
  ".react-flow__node-input",
  ".react-flow__node-default",
  ".react-flow__node-output",
  ".react-flow__node-group",
  ".react-flow__edge.animated",
  ".react-flow__edge-textwrapper",
];

function subset(css) {
  // A flat, comment-stripped rule scan. base.css has no @media or nesting.
  const out = [];
  const found = new Set();
  const body = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(body))) {
    const selectors = m[1]
      .split(",")
      .map((s) => s.trim().replace(/^\.react-flow\s+/, ""))
      .filter(Boolean);
    const keep = selectors.filter(
      (s) => KEEP.some((k) => s === k || s.startsWith(`${k} `) || s.startsWith(`${k}.`) || s.startsWith(`${k}:`)) &&
        !DROP.some((d) => s.startsWith(d)),
    );
    if (!keep.length) continue;
    for (const s of keep) for (const k of KEEP) if (s === k || s.startsWith(`${k}`)) found.add(k);
    // A declaration that reads a --xy-* token is a declaration the captured
    // markup cannot honour: those tokens are declared on `.react-flow`, which
    // does not travel. Worse than missing — `.react-flow__edge-path`'s
    // `stroke: var(--xy-edge-stroke, ...)` OUTRANKS a stroke presentation
    // attribute, so keeping it repaints all 705 boards' wires grey.
    const decls = m[2]
      .split(";")
      .map((d) => d.trim())
      .filter((d) => d && !d.includes("var(--xy-"))
      .join(";\n  ");
    if (!decls) continue;
    out.push(`${keep.join(",\n")} {\n  ${decls};\n}`);
  }
  const missing = KEEP.filter((k) => !found.has(k));
  if (missing.length) {
    throw new Error(
      `@xyflow/react's stylesheet no longer defines: ${missing.join(", ")}.\n` +
        "The static subset in dist/board.css would silently lose those rules — " +
        "check what upstream renamed before shipping this.",
    );
  }
  return out.join("\n\n");
}

const xyflowCss = readFileSync(require.resolve("@xyflow/react/dist/base.css"), "utf8");
const theme = readFileSync(resolve(app, "src/theme.css"), "utf8");
const board = readFileSync(resolve(app, "src/board.css"), "utf8");

const banner = `/* vocab-boards — dist/board.css
 * GENERATED by apps/vocab-boards/scripts/build-css.mjs. Do not edit.
 * Everything a captured .react-flow__viewport needs to render in a bare page:
 * theme tokens, the board ink, and the positioning rules from
 * @xyflow/react@${require("@xyflow/react/package.json").version} with the
 * .react-flow ancestor stripped so they match standalone markup.
 */\n`;

const css = [
  banner,
  theme.trim(),
  "",
  "/* --- @xyflow/react, static subset ------------------------------------- */",
  subset(xyflowCss),
  "",
  "/* --- vocab-boards ------------------------------------------------------ */",
  board.trim(),
  "",
].join("\n");

mkdirSync(resolve(app, "dist"), { recursive: true });
writeFileSync(resolve(app, "dist/board.css"), css);
console.log(`dist/board.css — ${css.length} bytes`);
